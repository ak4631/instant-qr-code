package com.akash.qrdrawer.data

import android.content.Context
import android.graphics.Bitmap
import android.graphics.BitmapFactory
import android.net.Uri
import android.util.Base64
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.withContext
import org.json.JSONArray
import org.json.JSONObject
import java.io.ByteArrayOutputStream
import java.io.File
import java.util.UUID

class QrRepository(context: Context) {
    private val appContext = context.applicationContext
    private val dao = QrDatabase.get(appContext).qrDao()
    private val imageDir get() = File(appContext.filesDir, IMAGE_DIR).apply { mkdirs() }

    val qrCodes: Flow<List<QrCode>> = dao.observeAll()

    suspend fun all(): List<QrCode> = dao.getAll()

    suspend fun get(id: Long): QrCode? = dao.get(id)

    suspend fun save(qr: QrCode): Long = dao.save(qr)

    suspend fun delete(qr: QrCode) {
        dao.delete(qr.id)
        qr.originalImagePath?.let { path -> withContext(Dispatchers.IO) { imageFile(path)?.delete() } }
    }

    /** Persists [orderedIds] as the new sort order. The default QR still sorts first. */
    suspend fun reorder(orderedIds: List<Long>) {
        val byId = dao.getAll().associateBy(QrCode::id)
        dao.updateAll(orderedIds.mapIndexedNotNull { index, id -> byId[id]?.copy(sortOrder = index) })
    }

    /**
     * Copies a picked image into app-private storage (never the gallery) so it can be shown as-is
     * when the QR could not be decoded. Returns the stored file name.
     */
    suspend fun storeImage(uri: Uri): String = withContext(Dispatchers.IO) {
        val bitmap = decodeSampled(uri) ?: error("Could not read the image")
        writePng(bitmap)
    }

    fun imageFile(name: String?): File? {
        if (name.isNullOrBlank()) return null
        // Stored names are generated by us; reject anything that could escape the image directory.
        if (name.contains('/') || name.contains("..")) return null
        return File(imageDir, name).takeIf(File::exists)
    }

    suspend fun exportTo(uri: Uri): Int = withContext(Dispatchers.IO) {
        val qrs = dao.getAll()
        val array = JSONArray()
        qrs.forEach { qr ->
            array.put(JSONObject().apply {
                put("label", qr.label)
                put("bank", qr.bank)
                put("upiId", qr.upiId)
                put("payload", qr.payload)
                put("color", qr.color)
                put("note", qr.note)
                put("isDefault", qr.isDefault)
                put("sortOrder", qr.sortOrder)
                imageFile(qr.originalImagePath)?.let { put("image", Base64.encodeToString(it.readBytes(), Base64.NO_WRAP)) }
            })
        }
        val root = JSONObject().apply {
            put("format", BACKUP_FORMAT)
            put("version", BACKUP_VERSION)
            put("exportedAt", System.currentTimeMillis())
            put("qrs", array)
        }
        val stream = appContext.contentResolver.openOutputStream(uri, "wt") ?: error("Could not open the file")
        stream.use { it.write(root.toString(2).toByteArray()) }
        qrs.size
    }

    /** Adds QRs from a backup file, skipping ones whose payload already exists. Returns the number added. */
    suspend fun importFrom(uri: Uri): Int = withContext(Dispatchers.IO) {
        val stream = appContext.contentResolver.openInputStream(uri) ?: error("Could not open the file")
        val bytes = stream.use { it.readBytes() }
        require(bytes.size <= MAX_BACKUP_BYTES) { "Backup file is too large" }
        val root = runCatching { JSONObject(String(bytes)) }.getOrElse { error("Not a QR Quick Drawer backup") }
        require(root.optString("format") == BACKUP_FORMAT) { "Not a QR Quick Drawer backup" }
        val entries = root.optJSONArray("qrs") ?: JSONArray()

        val existing = dao.getAll()
        val knownPayloads = existing.map(QrCode::payload).filter(String::isNotBlank).toMutableSet()
        var hasDefault = existing.any(QrCode::isDefault)
        var added = 0
        for (index in 0 until entries.length()) {
            val item = entries.optJSONObject(index) ?: continue
            val label = item.optString("label").trim().take(MAX_FIELD_LENGTH)
            val payload = item.optString("payload").take(MAX_PAYLOAD_LENGTH)
            if (label.isEmpty()) continue
            if (payload.isNotBlank() && !knownPayloads.add(payload)) continue
            val imageName = item.optString("image").takeIf(String::isNotEmpty)?.let { encoded ->
                runCatching {
                    val raw = Base64.decode(encoded, Base64.DEFAULT)
                    val bitmap = BitmapFactory.decodeByteArray(raw, 0, raw.size) ?: return@runCatching null
                    writePng(bitmap)
                }.getOrNull()
            }
            if (payload.isBlank() && imageName == null) continue
            val isDefault = item.optBoolean("isDefault") && !hasDefault
            if (isDefault) hasDefault = true
            dao.save(
                QrCode(
                    label = label,
                    bank = item.optString("bank").trim().take(MAX_FIELD_LENGTH),
                    upiId = item.optString("upiId").trim().take(MAX_FIELD_LENGTH),
                    payload = payload,
                    color = item.optInt("color", QR_COLORS.first()),
                    note = item.optString("note").take(MAX_NOTE_LENGTH),
                    isDefault = isDefault,
                    originalImagePath = imageName,
                ),
            )
            added++
        }
        added
    }

    private fun decodeSampled(uri: Uri): Bitmap? {
        val resolver = appContext.contentResolver
        val bounds = BitmapFactory.Options().apply { inJustDecodeBounds = true }
        resolver.openInputStream(uri)?.use { BitmapFactory.decodeStream(it, null, bounds) }
        var sample = 1
        while (maxOf(bounds.outWidth, bounds.outHeight) / (sample * 2) >= MAX_IMAGE_EDGE) sample *= 2
        val options = BitmapFactory.Options().apply { inSampleSize = sample }
        return resolver.openInputStream(uri)?.use { BitmapFactory.decodeStream(it, null, options) }
    }

    private fun writePng(bitmap: Bitmap): String {
        val name = "${UUID.randomUUID()}.png"
        val bytes = ByteArrayOutputStream().also { bitmap.compress(Bitmap.CompressFormat.PNG, 100, it) }.toByteArray()
        File(imageDir, name).writeBytes(bytes)
        return name
    }

    companion object {
        const val MAX_FIELD_LENGTH = 80
        const val MAX_NOTE_LENGTH = 500
        const val MAX_PAYLOAD_LENGTH = 4096
        private const val MAX_BACKUP_BYTES = 50 * 1024 * 1024
        private const val MAX_IMAGE_EDGE = 1600
        private const val IMAGE_DIR = "qr_images"
        private const val BACKUP_FORMAT = "qr-quick-drawer"
        private const val BACKUP_VERSION = 1
    }
}
